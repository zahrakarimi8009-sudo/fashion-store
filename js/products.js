/* =========================================================
   بارگذاری محصولات از دیتابیس (فاز PHP)
   ------------------------------------------------------------
   - در هاست‌های PHP (XAMPP / cPanel)، داده‌ی واقعی از
     api/products.php می‌آید و روی داده‌های نمایشی جایگزین می‌شود.
   - اگر PHP موجود نباشد (مثلاً مرور مستقیم فایل‌ها)،
     داده‌های نمایشی حفظ می‌شوند و هیچ خطایی رخ نمی‌دهد.
   - صفحه‌ها پیش از رندر گرید، await این Promise می‌کنند.
   ========================================================= */
let _nilaLoadProducts = null;
function nilaLoadProducts() {
  if (!_nilaLoadProducts) {
    _nilaLoadProducts = (function () {
      let settled = false;
      const settle = () => { settled = true; };
      return new Promise((resolve) => {
        /* نگهبان زمان: صفحه هرگز بیش از ۱.۵ ثانیه منتظر نمی‌ماند */
        setTimeout(() => { if (!settled) { settle(); resolve(); } }, 1500);
        try {
          fetch('api/products.php', { cache: 'no-store' })
            .then((r) => (r && r.ok ? r.json() : Promise.reject(new Error('no-api'))))
            .then((data) => {
              if (!settled && Array.isArray(data) && data.length) {
                PRODUCTS.length = 0;
                PRODUCTS.push.apply(PRODUCTS, data);
              }
            })
            .catch(() => { /* بدون PHP: داده‌های نمایشی */ })
            .then(() => { if (!settled) { settle(); resolve(); } });
        } catch (e) {
          if (!settled) { settle(); resolve(); }
        }
      });
    })();
  }
  return _nilaLoadProducts;
}
